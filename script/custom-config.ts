import { mkdir } from "node:fs/promises"
import path from "node:path"

const root = path.resolve(import.meta.dir, "..")
const agentsSource = path.join(root, "custom-config/project/.opencode/agents")
const assetsRoot = path.join(root, "packages/core/src/plugin/custom")
const agentsAssets = path.join(assetsRoot, "agents")
const instructionAssetsDir = path.join(assetsRoot, "instructions")
const modulePath = path.join(root, "packages/core/src/plugin/custom-agents.ts")
const labelModulePath = path.join(root, "packages/tui/src/feature-plugins/sidebar/custom-agent-labels.ts")
const instructions = [
  {
    name: "coordination",
    source: path.join(root, "custom-config/project/.opencode/COORDINATION.md"),
    filename: "coordination.md",
  },
  { name: "globalAgents", source: path.join(root, "custom-config/user/AGENTS.md"), filename: "global-agents.md" },
  {
    name: "questionProtocol",
    source: path.join(root, "custom-config/user/question-protocol.md"),
    filename: "question-protocol.md",
  },
  {
    name: "sourceLicenses",
    source: path.join(root, "custom-config/project/04-zrodla-i-licencje.md"),
    filename: "source-licenses.md",
  },
] as const
const checkOnly = Bun.argv.includes("--check")
const files = (await Array.fromAsync(new Bun.Glob("*.md").scan({ cwd: agentsSource }))).toSorted()

if (files.length !== 67) throw new Error(`Expected 67 custom agent definitions, found ${files.length}.`)

const agentLabels = await Promise.all(
  files.map(async (file) => {
    const content = await Bun.file(path.join(agentsSource, file)).text()
    const description = content.match(/^description:\s*["']([^"']+)["']\s*$/m)?.[1]
    if (!description) throw new Error(`Expected an English display description in ${file}.`)
    return { id: file.slice(0, -".md".length), description }
  }),
)

const agentAssetFiles = (await Array.fromAsync(new Bun.Glob("*.md").scan({ cwd: agentsAssets }))).toSorted()
const missing = files.filter((file) => !agentAssetFiles.includes(file))
const extra = agentAssetFiles.filter((file) => !files.includes(file))
const stale = await Promise.all(
  files.map(async (file) => {
    const target = Bun.file(path.join(agentsAssets, file))
    if (!(await target.exists())) return file
    return (await Bun.file(path.join(agentsSource, file)).text()) === (await target.text()) ? undefined : file
  }),
)
const staleFiles = stale.filter((file): file is string => file !== undefined)
const staleInstructions = await Promise.all(
  instructions.map(async (item) => {
    const target = path.join(instructionAssetsDir, item.filename)
    if (!(await Bun.file(target).exists())) return item.name
    return (await Bun.file(item.source).text()) === (await Bun.file(target).text()) ? undefined : item.name
  }),
)
const staleInstructionNames = staleInstructions.filter((name): name is string => name !== undefined)
const config = await Bun.file(path.join(root, "custom-config/project/opencode.jsonc")).json()
if (typeof config.default_agent !== "string") throw new Error("custom-config/project/opencode.jsonc must define default_agent.")

const instructionImports = instructions.map(
  (item) => `import instruction_${item.name} from ${JSON.stringify(`./custom/instructions/${item.filename}`)} with { type: "text" }`,
)
const generated = [
  "// Generated by script/custom-config.ts. Run `bun run custom-config:sync` after changing the packaged defaults.",
  ...files.map((file, index) => `import agent${index} from ${JSON.stringify(`./custom/agents/${file}`)} with { type: "text" }`),
  ...instructionImports,
  "",
  `export const CustomDefaultAgent = ${JSON.stringify(config.default_agent)}`,
  "",
  "export const CustomAgentFiles = [",
  ...files.map((file, index) => `  { filename: ${JSON.stringify(file)}, content: agent${index} },`),
  "] as const",
  "",
  "export const CustomInstructions = {",
  ...instructions.map((item) => `  ${item.name}: instruction_${item.name},`),
  "} as const",
  "",
].join("\n")
const generatedLabels = [
  "// Generated by script/custom-config.ts. Run `bun run custom-config:sync` after changing custom agent descriptions.",
  "export const CUSTOM_AGENT_LABELS: Readonly<Record<string, string>> = {",
  ...agentLabels.map((agent) => `  ${JSON.stringify(agent.id)}: ${JSON.stringify(agent.description)},`),
  "} as const",
  "",
].join("\n")
const generatedMatches = (await Bun.file(modulePath).text().catch(() => "")) === generated
const generatedLabelsMatch = (await Bun.file(labelModulePath).text().catch(() => "")) === generatedLabels
const synchronized =
  missing.length === 0 &&
  extra.length === 0 &&
  staleFiles.length === 0 &&
  staleInstructionNames.length === 0 &&
  generatedMatches &&
  generatedLabelsMatch

if (checkOnly) {
  if (!synchronized) {
    throw new Error(
      [
        "The built-in custom config is out of sync.",
        ...missing.map((file) => `Missing packaged agent: ${file}`),
        ...extra.map((file) => `Unexpected packaged agent: ${file}`),
        ...staleFiles.map((file) => `Out-of-date packaged agent: ${file}`),
        ...staleInstructionNames.map((name) => `Out-of-date instruction asset: ${name}`),
        ...(generatedMatches ? [] : ["Generated custom-agents.ts is out of date."]),
        ...(generatedLabelsMatch ? [] : ["Generated custom-agent-labels.ts is out of date."]),
        "Run `bun run custom-config:sync` to update the embedded assets.",
      ].join("\n"),
    )
  }
  console.log(`Verified ${files.length} embedded custom agents and ${instructions.length} instruction assets.`)
  process.exit(0)
}

if (extra.length > 0) throw new Error(`Remove unexpected packaged agents before syncing: ${extra.join(", ")}`)
await mkdir(agentsAssets, { recursive: true })
await mkdir(instructionAssetsDir, { recursive: true })
await Promise.all(files.map((file) => Bun.write(path.join(agentsAssets, file), Bun.file(path.join(agentsSource, file)))))
await Promise.all(
  instructions.map((item) => Bun.write(path.join(instructionAssetsDir, item.filename), Bun.file(item.source))),
)
await Bun.write(modulePath, generated)
await Bun.write(labelModulePath, generatedLabels)
console.log(`Synced ${files.length} custom agents, sidebar labels, and ${instructions.length} instruction assets.`)
